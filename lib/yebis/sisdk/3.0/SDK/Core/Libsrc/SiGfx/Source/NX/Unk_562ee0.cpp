// 0x7100563620: an NVN memory pool's flags for a kind of resource and its
// usage (the kind isn't used). The CPU's access is chosen by bit 16 first,
// then 17 (the selects' nesting).
u32 Unk_563620(u32 kind, u32 a1, u32 a2, u32 a3) {
    u32 flags = 0;
    if (a1 < 2) {
        flags = 0x21;
    }
    if (a1 == 2) {
        flags |= 0x24;
    }
    if (a1 == 3) {
        flags |= 8;
    }
    if (a2 & 0x20) {
        flags |= 0x80;
    } else if (a2 & 0x4000) {
        flags |= 0x80;
    }
    if (a3 & 0x10000) {
        if (a3 & 0x20000) {
            flags = (flags & 0xf8) | 4;
        } else {
            flags = (flags & 0xf8) | 2;
        }
    } else if (a3 & 0x20000) {
        flags = (flags & 0xf8) | 4;
    }
    return flags;
}
